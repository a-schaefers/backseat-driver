const MEAN = 'def mean(xs):\n    return sum(xs) / len(xs)\n'

function seen(commit: string, skill: string, verdict: 'shown' | 'missed', level: Level, weight = 1): Observation {
  return { commit, project: 'stats', at: 1, skill, verdict, level, weight, note: `${skill} in ${commit}` }
}

function record(observations: Observation[], level: Level | null = null, extra: Partial<ProgressRecord> = {}): ProgressRecord {
  return { ...emptyRecord('python'), observations, level, ...extra }
}

