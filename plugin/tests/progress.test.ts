test('a commit is yours only when your email wrote it, alone, and by hand', async () => {
  const info = parseCommitInfo('abc1234def\0p1\0Me@Example.com\0Me\0Add mean\n\nBody.\n')
  expect(info).toEqual({ hash: 'abc1234def', parents: ['p1'], email: 'me@example.com', name: 'Me', message: 'Add mean\n\nBody.' })
  expect(parseCommitInfo('not a commit')).toBe(null)
  expect(identityOf('me@example.com\n', ' ME@example.com', '', 'not-an-email')).toEqual(['me@example.com'])
  expect(parseRecent('aaaaaaa\0me@example.com\nbbbbbbb\0guido@python.org\n')).toEqual([
    { hash: 'aaaaaaa', email: 'me@example.com' },
    { hash: 'bbbbbbb', email: 'guido@python.org' },
  ])

  expect(hasOtherAuthor('Add mean\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>')).toBe(true)
  expect(hasOtherAuthor('Add mean\n\nco-authored-by: Ada <ada@example.com>')).toBe(true)
  expect(hasOtherAuthor('Add mean\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)')).toBe(true)
  expect(hasOtherAuthor('Add mean\n\nGenerated by GitHub Copilot')).toBe(true)
  expect(hasOtherAuthor('Add mean\n\nThe code generated by the parser is cached.')).toBe(false)

  const patch = [
    'diff --git a/stats.py b/stats.py',
    '--- a/stats.py',
    '+++ b/stats.py',
    '@@ -0,0 +1,2 @@',
    '+def mean(xs):',
    '+    return sum(xs) / len(xs)',
    'diff --git a/package-lock.json b/package-lock.json',
    '+++ b/package-lock.json',
    '+{}',
    'diff --git a/README.md b/README.md',
    '+++ b/README.md',
    '+# Stats',
    'diff --git a/deploy.sh b/deploy.sh',
    '+++ b/deploy.sh',
    '+echo hi',
  ].join('\n')
  const files = addedLines(patch)
  // Lock files and files in no language are not judged.
  expect(files).toEqual([
    { path: 'stats.py', language: 'python', lines: ['def mean(xs):', '    return sum(xs) / len(xs)'] },
    { path: 'deploy.sh', language: 'shell', lines: ['echo hi'] },
  ])
  expect([...byLanguage(files).keys()]).toEqual(['python', 'shell'])

  const mine = { hash: 'abc1234', parents: ['p1'], email: 'me@example.com', name: 'Me', message: 'Add mean' }
  expect(judge(mine, ['me@example.com'], files).isYours).toBe(true)
  const refused = (verdict: ReturnType<typeof judge>): string => (verdict.isYours ? '' : verdict.reason)
  expect(refused(judge({ ...mine, email: 'guido@python.org', name: 'Guido' }, ['me@example.com'], files))).toBe('it was written by Guido <guido@python.org>')
  expect(refused(judge(mine, [], files))).toMatch('git has no user.email here')
  expect(refused(judge({ ...mine, parents: ['p1', 'p2'] }, ['me@example.com'], files))).toBe('it is a merge')
  expect(refused(judge({ ...mine, message: 'Add mean\n\nCo-Authored-By: Claude <noreply@anthropic.com>' }, ['me@example.com'], files))).toMatch('co-author')
  expect(refused(judge(mine, ['me@example.com'], []))).toBe('it adds no source code')
  const bulk = [{ path: 'vendor.py', language: 'python', lines: Array.from({ length: MAX_ADDED_LINES + 1 }, (_, index) => `x${index} = ${index}`) }]
  expect(refused(judge(mine, ['me@example.com'], bulk))).toMatch('reads as an import or generated code')
})

test('no level until five observations from two commits, and a first placement never outruns the evidence', async () => {
  const four = [seen('a', 'naming', 'shown', 'junior'), seen('a', 'loops', 'shown', 'junior'), seen('b', 'tests', 'shown', 'junior'), seen('b', 'errors', 'missed', 'junior')]
  expect(decideLevel(record(four), 'junior').level).toBe(null)
  // Five, but all from one commit.
  expect(decideLevel(record([...four.slice(0, 2), seen('a', 'x', 'shown', 'junior'), seen('a', 'y', 'shown', 'junior'), seen('a', 'z', 'shown', 'junior')]), 'junior').level).toBe(null)

  const five = [...four, seen('b', 'idioms', 'shown', 'junior')]
  const placed = decideLevel(record(five), 'junior')
  expect(placed.level).toBe('junior')
  expect(placed.isProvisional).toBe(true)
  expect(placed.reason).toBe('First placement, from 5 observations over 2 commits.')

  // The model says senior. The evidence supports junior, and junior it is.
  expect(decideLevel(record(five), 'senior').level).toBe('junior')
  // The model is more cautious than the evidence: its reading stands.
  expect(decideLevel(record(five), 'beginner').level).toBe('beginner')
})

test('a step up takes new evidence at the next level from two commits, and the model agreeing', async () => {
  const placed = { at: 1, from: null, to: 'junior' as const, reason: 'First placement.', observationCount: 5 }
  const base = Array.from({ length: 5 }, (_, index) => seen(`c${index % 2}`, `s${index}`, 'shown', 'junior'))
  const ahead = [seen('d', 'interfaces', 'shown', 'mid'), seen('d', 'tests', 'shown', 'mid'), seen('e', 'errors', 'shown', 'mid'), seen('e', 'design', 'shown', 'mid')]
  const atJunior = (observations: Observation[]): ProgressRecord => record([...base, ...observations], 'junior', { history: [placed] })

  expect(decideLevel(atJunior(ahead), 'mid').level).toBe('mid')
  // One step at a time, whatever the model says.
  expect(decideLevel(atJunior(ahead), 'senior').level).toBe('mid')
  // The model does not see it yet: no move.
  expect(decideLevel(atJunior(ahead), 'junior').level).toBe('junior')
  // The same evidence from one commit is one good afternoon, not a level.
  expect(decideLevel(atJunior(ahead.map(item => ({ ...item, commit: 'd' }))), 'mid').level).toBe('junior')
  // Work the tutor did not watch arrive counts half, so it takes twice as much.
  expect(decideLevel(atJunior(ahead.map(item => ({ ...item, weight: 0.5 }))), 'mid').level).toBe('junior')
})

test('a level comes back down when what it assumes is missed, and the skill is marked slipping', async () => {
  const placed = { at: 1, from: null, to: 'mid' as const, reason: 'Placed.', observationCount: 6 }
  const base = [...Array.from({ length: 5 }, (_, index) => seen(`c${index % 2}`, `s${index}`, 'shown', 'mid')), seen('c0', 'edge-cases', 'shown', 'junior')]
  const missed = [seen('f', 'edge-cases', 'missed', 'junior'), seen('g', 'error-handling', 'missed', 'mid')]
  const atMid = record([...base, ...missed], 'mid', { history: [placed], isProvisional: false })

  const decided = decideLevel(atMid, 'mid')
  // Missed outweighs what was shown at this level since: down a step, even though the model held its ground.
  expect(decided.level).toBe('junior')
  expect(decided.reason).toBe('Down a step: 2 recent observations show mid work not yet solid (edge-cases, error-handling).')
  expect(skillStates(atMid).slipping).toEqual(['edge-cases'])
  expect(skillStates(atMid).working).toEqual(['error-handling'])

  // One bad commit alone does not.
  expect(decideLevel(record([...base, ...missed.map(item => ({ ...item, commit: 'f' }))], 'mid', { history: [placed] }), 'junior').level).toBe('mid')
})

test('withAssessment records what was seen once per commit, and keeps the history of every change', async () => {
  const first = withAssessment(emptyRecord('python'), SAW, [{ hash: 'a'.repeat(40), short: 'aaaaaaa', weight: 1 }], 'stats', 10)
  expect(first.record.observations.map(item => `${item.commit.slice(0, 7)} ${item.verdict} ${item.skill} x${item.weight}`)).toEqual(['aaaaaaa missed edge-cases x1', 'aaaaaaa shown naming x1'])
  expect(first.record.report?.why).toBe('Small, working functions with clear names.')
  expect(first.change).toBe(null)
  expect(levelPhrase(first.record)).toBe('no level yet: 2 of 5 observations, from 1 of 2 commits')

  // The same commit again, from another project or another session, adds nothing.
  expect(withAssessment(first.record, SAW, [{ hash: 'a'.repeat(40), short: 'aaaaaaa', weight: 1 }], 'fork', 20).record).toBe(first.record)

  const more: Assessment = { ...SAW, observations: [...SAW.observations, { ...SAW.observations[1]!, skill: 'idioms' }, { ...SAW.observations[1]!, skill: 'tests' }] }
  const second = withAssessment(first.record, more, [{ hash: 'b'.repeat(40), short: 'bbbbbbb', weight: 0.5 }], 'stats', 30)
  expect(second.record.level).toBe('junior')
  expect(second.change).toEqual({ at: 30, from: null, to: 'junior', reason: 'First placement, from 6 observations over 2 commits.', observationCount: 6 })
  expect(second.record.history).toEqual([second.change!])
  expect(parseRecord(JSON.parse(JSON.stringify(second.record)), 'python')).toEqual(second.record)
  expect(parseRecord({ ...second.record, language: 'rust' }, 'python')).toEqual(emptyRecord('python'))

  expect(recordText(second.record)).toMatch('Python: junior (provisional)\nWhy: Small, working functions with clear names.\nFor the next level: Handle the empty input on purpose, and test it.')
  expect(progressText([second.record])).toMatch('- Python: observed level junior (provisional).')
  expect(progressText([first.record])).toBe('')
})

